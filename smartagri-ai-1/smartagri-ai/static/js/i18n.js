const SMARTAGRI_VOICE_LOCALE = { en: "en-IN", te: "te-IN", ta: "ta-IN", hi: "hi-IN" };

function smartagriGetLang() {
  return localStorage.getItem("smartagri_lang") || "en";
}

function smartagriSetLang(lang) {
  localStorage.setItem("smartagri_lang", lang);
}

function smartagriApplyTranslations() {
  const lang = smartagriGetLang();
  const dict = SMARTAGRI_I18N[lang] || SMARTAGRI_I18N.en;
  document.documentElement.setAttribute("lang", lang);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });
  const langLabel = document.getElementById("currentLangLabel");
  if (langLabel) {
    const names = { en: "English", te: "తెలుగు", ta: "தமிழ்", hi: "हिन्दी" };
    langLabel.textContent = names[lang];
  }
}

document.addEventListener("DOMContentLoaded", smartagriApplyTranslations);
